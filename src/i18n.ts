export const DICT = { en, it, uk };
export type Key = keyof typeof en;
export const LANGS: Lang[] = ['it', 'en', 'uk'];

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function pickLang(browser: string | undefined, saved: string | null): Lang {
  if (saved === 'it' || saved === 'en' || saved === 'uk') return saved;
  const b = (browser ?? '').toLowerCase();
  if (b.startsWith('it')) return 'it';
  if (b.startsWith('uk') || b.startsWith('ru')) return 'uk';
  return 'en';
}

